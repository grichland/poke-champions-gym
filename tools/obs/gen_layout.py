"""Writes obs/src/layout.rs from obs/features_proposed.csv: every feature id with its block, offset, size,
repeats, encoding and value range. Standard library only. Run from the repo root: python tools/obs/gen_layout.py"""

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CSV = ROOT / "obs" / "features_proposed.csv"
OUT = ROOT / "obs" / "src" / "layout.rs"

BLOCKS = {  # (name prefix, kind) -> Rust block
    ("pokemon", "float"): "Row",
    ("pokemon", "id"): "RowIds",
    ("field", "float"): "Field",
    ("last_turn", "float"): "Last",
    ("last_turn", "id"): "LastIds",
    ("action_mask", "float"): "Mask",
    ("learnset_table", "float"): "Table",
}
TOTALS = {"Row": 300, "RowIds": 10, "Field": 66, "Last": 17, "LastIds": 4, "Mask": 11, "Table": 0}


def value_range(scale: str, kind: str) -> tuple[float, float]:
    if kind == "id":
        return 0.0, 1e9
    if "-1.5..1.5" in scale:
        return -1.5, 1.5
    if "-1..1" in scale:
        return -1.0, 1.0
    if "clip 2" in scale or "0-2" in scale:
        return 0.0, 2.0
    return 0.0, 1.0


def parse_index(index: str):
    """(offset, slot base, slot stride) from the CSV's index text."""
    m = re.fullmatch(r"(\d+)\+(\d+)\*slot\+(\d+)(?:\.\.(\d+))?", index)
    if m:
        return int(m.group(3)), int(m.group(1)), int(m.group(2))
    m = re.fullmatch(r"(?:last_ids|ids)\[(\d+)(?::(\d+))?\]", index)
    if m:
        return int(m.group(1)), None, None
    m = re.fullmatch(r"(\d+)(?:-(-?\d+))?", index)
    if m:
        return int(m.group(1)), None, None
    raise ValueError(f"unreadable index {index!r}")


def main() -> int:
    rows = list(csv.DictReader(open(CSV, encoding="utf-8", newline="")))
    feats = []
    base = stride = None
    for r in rows:
        kind = "id" if r["encoding"].startswith("embedding") else "float"
        block = BLOCKS[(r["name"].split(".")[0], kind)]
        offset, b, s = parse_index(r["index"])
        size, repeats = int(r["size"]), int(r["repeats"])
        if b is not None:
            assert base in (None, b) and stride in (None, s), r["id"]
            base, stride = b, s
        lo, hi = value_range(r["scale_range"], kind)
        ident = re.sub(r"[^A-Za-z0-9]", "_", r["id"])
        feats.append(dict(id=r["id"], ident=ident, name=r["name"], block=block, offset=offset, size=size,
                          repeats=repeats, slot=b is not None, enc=r["encoding"], scale=r["scale_range"], lo=lo, hi=hi))
    # totals per block (slot features: base + stride x 4)
    used = {k: 0 for k in TOTALS}
    for f in feats:
        span = f["size"] * (1 if f["slot"] else f["repeats"])
        end = (base + stride * 4) if f["slot"] else f["offset"] + span
        used[f["block"]] = max(used[f["block"]], end)
    assert used == TOTALS, used
    assert len(feats) == 149, len(feats)

    def lit(x: str) -> str:
        return '"' + x.replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = [
        "//! Generated by tools/obs/gen_layout.py from obs/features_proposed.csv. Do not edit by hand.",
        "",
        "#![allow(dead_code)]",
        "",
        "use crate::Block;",
        "",
    ]
    for k, v in TOTALS.items():
        out.append(f"pub const {k.upper()}_LEN: usize = {v};")
    out += [
        f"/// first float of move slot 0 in a Pokémon row",
        f"pub const MOVE_BASE: usize = {base};",
        f"/// floats per move slot",
        f"pub const MOVE_STRIDE: usize = {stride};",
        "",
        "/// One feature of the CSV.",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct Feature {",
        "    pub id: &'static str,",
        "    pub name: &'static str,",
        "    pub block: Block,",
        "    /// offset in its block; for move-slot features the offset inside the slot",
        "    pub offset: usize,",
        "    pub size: usize,",
        "    /// 4 for move-slot features (at MOVE_BASE + MOVE_STRIDE * slot + offset), else 1",
        "    pub repeats: usize,",
        "    pub slot: bool,",
        "    pub encoding: &'static str,",
        "    pub scale: &'static str,",
        "    pub lo: f32,",
        "    pub hi: f32,",
        "}",
        "",
        f"pub static FEATURES: [Feature; {len(feats)}] = [",
    ]
    for f in feats:
        out.append(
            f"    Feature {{ id: {lit(f['id'])}, name: {lit(f['name'])}, block: Block::{f['block']}, offset: {f['offset']}, "
            f"size: {f['size']}, repeats: {f['repeats']}, slot: {str(f['slot']).lower()}, encoding: {lit(f['enc'])}, "
            f"scale: {lit(f['scale'])}, lo: {f['lo']:.1f}, hi: {f['hi']:.1f} }},"
        )
    out += ["];", "", "// offset of each feature in its block (move-slot features: inside the slot)"]
    for f in feats:
        out.append(f"pub const {f['ident']}: usize = {f['offset']};")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(feats)} features, totals {used}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
