"""Writes obs/src/learnsets.rs: for every CG species, the CG moves it can learn, from Showdown's Champions
learnsets (data/mods/champions/learnsets.ts). A species with no entry (a Mega, a form) uses the entry of the
species it Mega Evolves from, else of its base species. Standard library only.

Run from the repo root: python tools/obs/gen_learnsets.py [path to pokemon-showdown]"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SHOWDOWN = Path(r"C:\Users\user\Code\pokemon_champions\pcsa\.tools\vendor\pokemon-showdown")
GENERATED = ROOT / "engine" / "src" / "sim" / "data" / "generated.rs"
OUT = ROOT / "obs" / "src" / "learnsets.rs"


def table(text: str, name: str) -> list[str]:
    start = text.index(f"pub static {name}:")
    end = text.index("\n];", start)
    return [ln for ln in text[start:end].splitlines()[1:] if ln.strip()]


def learnsets(path: Path) -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    cur = None
    inside = False
    for ln in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\t([a-z0-9]+): \{", ln)
        if m:
            cur, inside = m.group(1), False
            out.setdefault(cur, set())
            continue
        if re.match(r"^\t\tlearnset: \{", ln):
            inside = True
            continue
        if inside and re.match(r"^\t\t\}", ln):
            inside = False
            continue
        m = re.match(r"^\t\t\t([a-z0-9]+): \[", ln)
        if inside and m and cur:
            out[cur].add(m.group(1))
    return out


def main() -> int:
    showdown = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SHOWDOWN
    src = showdown / "data" / "mods" / "champions" / "learnsets.ts"
    commit = (showdown / ".git" / "HEAD").read_text().strip() if (showdown / ".git" / "HEAD").is_file() else "unknown"
    gen = GENERATED.read_text(encoding="utf-8")
    species = []
    for ln in table(gen, "SPECIES"):
        sid = re.search(r'id: "([a-z0-9]*)"', ln).group(1)
        base = int(re.search(r"base_species: SpeciesId\((\d+)\)", ln).group(1))
        mf = re.search(r"mega_from: Some\(SpeciesId\((\d+)\)\)", ln)
        species.append((sid, base, int(mf.group(1)) if mf else None))
    moves = [re.search(r'id: "([a-z0-9]*)"', ln).group(1) for ln in table(gen, "MOVES")]
    move_index = {m: i for i, m in enumerate(moves) if m}
    ls = learnsets(src)
    words = (len(moves) + 63) // 64
    rows, own, borrowed, empty, unknown_moves = [], 0, 0, 0, set()
    for sid, base, mega_from in species:
        key = sid
        if not ls.get(key):
            key = species[mega_from][0] if mega_from is not None else species[base][0]
            borrowed += 1
        else:
            own += 1
        bits = [0] * words
        for mv in ls.get(key, ()):
            if mv in move_index:
                i = move_index[mv]
                bits[i // 64] |= 1 << (i % 64)
            else:
                unknown_moves.add(mv)
        if not any(bits):
            empty += 1
        rows.append(bits)
    lines = [
        "//! Generated by tools/obs/gen_learnsets.py from Showdown's data/mods/champions/learnsets.ts. Do not edit.",
        f"//! Showdown {commit}; {own} species with their own entry, {borrowed} from the species they Mega Evolve",
        f"//! from or their base species, {empty} with none; {len(unknown_moves)} learnset moves are not CG moves.",
        "",
        f"pub const LEARNSET_WORDS: usize = {words};",
        "/// per SpeciesId: bit MoveId.0 is set when the species can learn the move",
        f"pub static LEARNSET: [[u64; {words}]; {len(rows)}] = [",
    ]
    for (sid, _, _), bits in zip(species, rows):
        lines.append("    [" + ", ".join(f"0x{b:016x}" for b in bits) + f"], // {sid}")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(rows)} species, {own} own, {borrowed} borrowed, {empty} empty, {len(unknown_moves)} non-CG moves")
    return 0


if __name__ == "__main__":
    sys.exit(main())
