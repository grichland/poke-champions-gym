"""13-report.py: render out/diff.json (from 12-compare.py) as 09-data-diff.md. Run from this folder."""
import json
import os
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, 'out', 'diff.json'), encoding='utf-8'))
S, diffs = D['summary'], D['diffs']

# differences already known from reading; the pipeline must find each one
KNOWN = [
    ('moves', 'makeitrain', 'basePower', 120, 95), ('moves', 'makeitrain', 'accuracy', 95, 100),
    ('megas', 'garchompmegaz', 'ability', 'LEVITATE', 'SANDFORCE'), ('megas', 'golisopodmega', 'ability', 'TOUGHCLAWS', 'EMERGENCYEXIT'),
    ('megas', 'starmiemega', 'baseStats.atk', 100, 140), ('megas', 'drampamega', 'baseStats.spd', 116, 114),
    ('moves', 'slash', 'basePower', 80, 70), ('moves', 'meteorassault', 'basePower', 170, 150),
    ('moves', 'crabhammer', 'basePower', 100, 95), ('moves', 'crabhammer', 'accuracy', 95, 90),
    ('moves', 'swagger', 'accuracy', 85, 90), ('moves', 'syrupbomb', 'basePower', 60, 90), ('moves', 'growth', 'type', 'GRASS', 'NORMAL'),
    ('items', 'lightclay', 'exists in enum', True, False), ('items', 'quickclaw', 'exists in enum', True, False),
    ('items', 'leek', 'exists in enum', True, False), ('abilities', 'auraguard', 'exists in enum', True, False),
]


def cell(v):
    if v is None:
        return '—'
    if isinstance(v, (list, tuple)):
        return '; '.join(cell(x) for x in v) if v and isinstance(v[0], (list, tuple)) else ' '.join(str(x) for x in v)
    return str(v).replace('|', '\\|')


L = []
w = L.append
w('# 09 — Mechanical data diff: poke-engine (champions,bss) vs Showdown `champions` mod\n')
w('Generated by `13-report.py` from `out/diff.json`. Do not edit by hand; rerun 11 → 12 → 13.\n')
w('## How the data were obtained\n')
w('- **Engine: compiled, not parsed.** poke-engine at f7b147f was copied to `work/engine/` (git-ignored) and the '
  'program `11-engine_dump.rs` was added as a Cargo example and built with `--no-default-features --features champions,bss` '
  '(script `11-build_engine_dump.sh`; the llvm-mingw linker needed `libgcc`/`libgcc_eh` stand-ins, see the script). '
  'It reads the live `MOVES` table, so every `cfg!` branch and `apply_champions_modifiers` are applied by the compiler. '
  'Enums (`Choices`, `Items`, `Abilities`, `PokemonName`, `PokemonType`, `PokemonNature`) are enumerated by integer value; '
  'Megas by calling `PokemonName::mega_evolve_target(item)` for every (species, item) pair; per-form base stats by '
  '`PokemonName::base_stats()`; the type chart by `type_effectiveness_modifier()` on mono-typed defenders; natures by '
  '`calculate_stats_from_base_stats()` against a Serious-nature baseline. Output: `out/engine.json`.')
w('- **Showdown:** `out/showdown-champions.json` from `09-dump_showdown.js` (unchanged). Only LEGAL entries are compared.')
w('- **Compare:** `12-compare.py` → `out/diff.json` (every record has `cat, id, field, showdown, engine, cls, note`).\n')
w('Classes: **real** = the data disagree; **representation** = same meaning, different encoding; '
  '**needs-reading** = one side expresses it as a function / move-specific code, so equality cannot be decided from data.\n')

w('## Summary\n')
w('| category | entries compared | differences | real | representation | needs-reading |')
w('|---|---|---|---|---|---|')
bycat = defaultdict(Counter)
for d in diffs:
    bycat[d['cat']][d['cls']] += 1
cmap = {'moves': 'moves', 'megas': 'megas', 'species': 'species(name enum)', 'items': 'items', 'abilities': 'abilities',
        'typechart': 'typechart pairs', 'natures': 'natures'}
for cat, key in cmap.items():
    c = bycat[cat]
    w(f"| {cat} | {S['compared'].get(key, 0)} | {sum(c.values())} | {c['real']} | {c['representation']} | {c['needs-reading']} |")
w(f"\nAlso compared: base stats of {S['compared'].get('species(base stats held by engine)', 0)} legal non-Mega forms the engine "
  f"holds stats for (Minior-Meteor, Eiscue-Noice, Palafin, Palafin-Hero): no differences. The engine move table has "
  f"{S['engine_moves_total']} entries; all 515 legal moves exist in it.\n")

w('### Differences per field\n')
w('| category | field | comparisons | real | representation | needs-reading |')
w('|---|---|---|---|---|---|')
byf = defaultdict(Counter)
for d in diffs:
    byf[(d['cat'], d['field'])][d['cls']] += 1
fc = S['fields_compared']
rows = sorted(set(k for k in fc) | {f'{c}:{f}' for c, f in byf})
for k in rows:
    cat, field = k.split(':', 1)
    c = byf[(cat, field)]
    w(f"| {cat} | {field} | {fc.get(k, '')} | {c['real']} | {c['representation']} | {c['needs-reading']} |")

w('\n### Sanity check against differences known from reading\n')
w('| category | id | field | expected (Showdown / engine) | found |')
w('|---|---|---|---|---|')
allfound = True
for cat, id_, field, sv, ev in KNOWN:
    hit = [d for d in diffs if d['cat'] == cat and d['id'] == id_ and d['field'] == field]
    ok = bool(hit) and hit[0]['showdown'] == sv and hit[0]['engine'] == ev
    allfound &= ok
    w(f"| {cat} | {id_} | {field} | {sv} / {ev} | {'yes' if ok else 'NO: ' + json.dumps(hit)} |")
w(f"\nAll known differences found: **{'yes' if allfound else 'NO'}**.\n")

w('## Field mapping (engine → Showdown)\n')
w('''| engine (`Choice`, after `apply_champions_modifiers`) | Showdown move | notes |
|---|---|---|
| `move_type` | `type` (upper-cased) | |
| `category` | `category` | |
| `base_power` | `basePower` | moves with `basePowerCallback`/`damageCallback`/`damage`/`ohko` → needs-reading |
| `accuracy` (f32) | `accuracy` (`true` = never misses) | `true` vs 100 = representation |
| `priority` | `priority` | |
| `target` (User/Opponent) | `target` | self, adjacentAllyOrSelf, allies, allyTeam, allySide, adjacentAlly → User; `all` → field (representation, engine has no field target); the rest → Opponent |
| `flags.{bite,bullet,charge,contact,heal,powder,protect,pulse,punch,recharge,reflectable,slicing,sound,wind}` | `flags.<same name>` | |
| `flags.drag` | `forceSwitch` | |
| `flags.pivot` | `selfSwitch` (true / copyvolatile / shedtail) | |
| `increased_crit_ratio()` (code list) | `critRatio` 2 | |
| `guaranteed_crit()` (code list) | `willCrit` | |
| `multi_hit()` (code list) | `multihit`: 2→DoubleHit, 3→TripleHit, [2,5]→TwoToFiveHits, 10→PopulationBomb; Triple Axel→TripleAxel | `multiaccuracy` noted as representation |
| `crash` | `hasCrashDamage` | existence only (engine stores a fraction) |
| `boost {target, boosts}` | `boosts` (target from move target), `self.boosts`, `selfBoost.boosts` (User) | engine `StatBoosts` has no evasion |
| `status {target, status}` | `status` (brn/par/slp/frz/psn/tox → BURN/PARALYZE/SLEEP/FREEZE/POISON/TOXIC) | |
| `volatile_status {target, ..}` | `volatileStatus` (target from move), `self.volatileStatus` (User) | `self.volatileStatus: mustrecharge` is the engine `recharge` flag, not compared here |
| `side_condition {target, ..}` | `sideCondition` or `slotCondition` (allySide→User, foeSide→Opponent) | |
| `heal {target, amount}` | `heal` [n,d] → n/d | `heal -1 on User` = Showdown `selfdestruct`; `heal -0.5 on User` = `mindBlownRecoil` |
| `drain`, `recoil` | `drain`, `recoil` [n,d] → n/d | tolerance 0.006 (engine 0.33 vs 33/100) |
| `secondaries [{chance, target, effect}]` | `secondaries [{chance, status / volatileStatus / boosts / self.boosts}]` | a 100% secondary on one side vs a primary effect on the other = representation; `onHit` secondaries → needs-reading |
| — | `pp` | **not in the engine** (PP is caller-supplied) |

Megas: engine `mega_evolve_target(species, item)` → `MegaEvolveData {id, types, ability, base_stats}`, compared with
Showdown `requiredItem`, `changesFrom`, `types` (engine TYPELESS second type dropped), `abilities['0']`, `baseStats`.
`PokemonName::base_stats()` (what stat recalculation actually uses) is compared separately as `baseStats(table)`.
''')

order = {'real': 0, 'needs-reading': 1, 'representation': 2}
titles = {'moves': 'Moves', 'megas': 'Mega forms', 'species': 'Species (name enum)', 'items': 'Items (enum existence)',
          'abilities': 'Abilities (enum existence)', 'typechart': 'Type chart', 'natures': 'Natures'}
for cat, title in titles.items():
    rows = sorted([d for d in diffs if d['cat'] == cat], key=lambda d: (order[d['cls']], d['id'], d['field']))
    w(f'## {title}: every difference ({len(rows)})\n')
    if not rows:
        w('No differences.\n')
        continue
    w('| class | id | field | Showdown | engine | note |')
    w('|---|---|---|---|---|---|')
    for d in rows:
        w(f"| {d['cls']} | {d['id']} | {d['field']} | {cell(d['showdown'])} | {cell(d['engine'])} | {cell(d['note']) if d['note'] else ''} |")
    w('')

w('## Showdown concepts the engine has no field for\n')
w('Showdown move flags with no engine flag (number of legal moves carrying each): ' +
  ', '.join(f'`{k}` {v}' for k, v in S['showdown_flags_not_in_engine'].items()) + '.\n')
w('Showdown move properties not compared (no engine data field; behaviour, if any, lives in engine code): ' +
  ', '.join(f'`{k}` {v}' for k, v in S['showdown_move_props_not_compared'].items()) + '.\n')
w('## Engine-only entries (information)\n')
w(f"- Engine Megas not legal in Showdown champions ({len(S['engine_megas_not_legal_in_showdown'])}): " + ', '.join(S['engine_megas_not_legal_in_showdown']))
w(f"- Engine `Items` members not in the legal list: {len(S['engine_items_not_legal_in_showdown'])}; "
  f"`Abilities` members not in the legal list: {len(S['engine_abilities_not_legal_in_showdown'])} (full lists in `out/diff.json`).\n")

w('''## Limits

- **PP** is not compared: the engine's `Choice` has no PP field (PP is supplied by the caller per move).
- **Behaviour is not compared.** Items and abilities are checked for enum existence only. Effects the engine implements
  in move-specific code (`choice_effects.rs`, `generate_instructions.rs`, `abilities.rs`) rather than in the `Choice`
  table are not evaluated; where such code exists and a field differs, the row is marked needs-reading. The scan for
  move-specific code is a text search for `Choices::<ID>` in `src/genx/*.rs` of the copy, not a semantic check, and it
  is used only for classification, never to hide a row.
- **Showdown functions** (`onHit`, `basePowerCallback`, `onBasePower`, `condition` handlers, …) are not evaluated; rows
  that depend on them are needs-reading (e.g. Tri Attack, Triple Axel power, Spirit Shackle trapping).
- **Field effects** — `weather`, `terrain`, `pseudoWeather`, Trick Room and similar — have no data field in the engine
  (they are code keyed on the move id), so only the move target is listed (as representation).
- **Durations, condition data, `ignoreImmunity`, `breaksProtect`, `ohko`, `thawsTarget`, `ignoreAbility`, Z/Max data**
  and the other properties listed above are not compared.
- **Move target** is reduced to User/Opponent/field; singles-irrelevant distinctions (allAdjacent vs normal, etc.) are
  not compared.
- **Species**: only the 392 legal ids' presence in `PokemonName`, the 82 legal Megas, and the four non-Mega forms the
  engine holds base stats for are compared. The engine holds no types, abilities, weights or base stats for ordinary
  species (the caller supplies them), so those are not comparable. Weight of Mega forms is not compared.
- **Type chart**: the 18 real types (324 pairs). Stellar/Typeless are not compared; Showdown's non-type immunities in
  `damageTaken` (brn, par, sandstorm, …) are not compared.
- **Natures**: plus/minus stat only, measured at level 100 on a single species; the 10%/-10% factors are not separately
  checked.
''')
open(os.path.join(HERE, '09-data-diff.md'), 'w', encoding='utf-8').write('\n'.join(L))
print('ok', len(L), 'lines; known all found:', allfound)
